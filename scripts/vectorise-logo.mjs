/**
 * Vectorises the CP monogram from the intro frame of CPV14 (t = 2.5s, where it is a
 * clean head-on gold outline on black). No redrawing: the shape is traced from pixels.
 *
 *   ffmpeg -ss 2.5 -i assets/source/CPV14.mp4 -frames:v 1 assets/contact/logo_2.5.png
 *   node scripts/vectorise-logo.mjs            -> debug image + component list
 *   node scripts/vectorise-logo.mjs --write    -> public/brand/logo.svg
 *
 * Method: threshold the glowing outline, label the dark regions it encloses, keep the
 * regions that are letter *bodies* (seed points below), dilate 1px, trace with potrace.
 * Where the P crosses the C the outline leaves a knockout gap, as in the flat mark.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PNG } from "pngjs";
import potrace from "potrace";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const SRC = path.join(__dirname, "../assets/contact/logo_2.5.png");
const CROP = { x: 130, y: 125, w: 430, h: 465 };
// Points (frame coords) that sit inside a letter body, one per enclosed body region.
const BODY_SEEDS = [
  [175, 280], // C left stroke
  [290, 172], // C top bar
  [290, 392], // C bottom bar
  [340, 245], // P bowl top-left (over C)
  [420, 240], // P bowl top
  [505, 330], // P bowl right
  [420, 455], // P bowl bottom
  [340, 300], // P left stroke (over C)
  [340, 520], // P stem
];

const png = PNG.sync.read(fs.readFileSync(SRC));
const { w, h } = CROP;
const lum = new Uint8Array(w * h);
for (let y = 0; y < h; y++)
  for (let x = 0; x < w; x++) {
    const i = ((y + CROP.y) * png.width + (x + CROP.x)) * 4;
    lum[y * w + x] = png.data[i]; // red channel carries the gold outline best
  }

const BAND = 70;
const band = new Uint8Array(w * h);
for (let i = 0; i < w * h; i++) band[i] = lum[i] > BAND ? 1 : 0;

// label non-band regions (4-connected)
const label = new Int32Array(w * h).fill(-1);
const comps = [];
for (let s = 0; s < w * h; s++) {
  if (band[s] || label[s] !== -1) continue;
  const id = comps.length;
  const stack = [s];
  label[s] = id;
  let area = 0, sx = 0, sy = 0, touchesEdge = false;
  while (stack.length) {
    const p = stack.pop();
    const x = p % w, y = (p / w) | 0;
    area++; sx += x; sy += y;
    if (x === 0 || y === 0 || x === w - 1 || y === h - 1) touchesEdge = true;
    for (const q of [p - 1, p + 1, p - w, p + w]) {
      if (q < 0 || q >= w * h) continue;
      if (Math.abs((q % w) - x) > 1) continue;
      if (!band[q] && label[q] === -1) { label[q] = id; stack.push(q); }
    }
  }
  comps.push({ id, area, cx: Math.round(sx / area) + CROP.x, cy: Math.round(sy / area) + CROP.y, touchesEdge });
}

const bodyIds = new Set(
  BODY_SEEDS.map(([x, y]) => label[(y - CROP.y) * w + (x - CROP.x)]).filter((id) => id >= 0)
);

// mask = body regions dilated by 1px (recovers the outer half of the outline band)
const mask = new Uint8Array(w * h);
for (let i = 0; i < w * h; i++) if (bodyIds.has(label[i])) mask[i] = 1;
const dil = mask.slice();
for (let y = 1; y < h - 1; y++)
  for (let x = 1; x < w - 1; x++) {
    const i = y * w + x;
    if (!mask[i] && (mask[i - 1] || mask[i + 1] || mask[i - w] || mask[i + w])) dil[i] = 1;
  }

const out = new PNG({ width: w, height: h });
for (let i = 0; i < w * h; i++) {
  const v = dil[i] ? 0 : 255;
  out.data[i * 4] = out.data[i * 4 + 1] = out.data[i * 4 + 2] = v;
  out.data[i * 4 + 3] = 255;
}
const maskPath = path.join(__dirname, "../assets/contact/logo_mask.png");
fs.writeFileSync(maskPath, PNG.sync.write(out));

if (!process.argv.includes("--write")) {
  console.log("components (area>200):");
  comps.filter((c) => c.area > 200).forEach((c) =>
    console.log(c.id, c.area, `@${c.cx},${c.cy}`, c.touchesEdge ? "edge" : "", bodyIds.has(c.id) ? "BODY" : "")
  );
  console.log("mask written:", maskPath);
  process.exit(0);
}

potrace.trace(maskPath, { threshold: 128, turdSize: 20, optTolerance: 0.4, alphaMax: 0.6 }, (err, svg) => {
  if (err) throw err;
  const d = svg.match(/ d="([^"]+)"/)[1];
  const file = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" fill="currentColor" role="img" aria-label="Concept Plus">
  <!-- Traced from CPV14.mp4 @ 0:02.5 by scripts/vectorise-logo.mjs. Replace with the official vector when available. -->
  <path fill-rule="evenodd" d="${d}"/>
</svg>
`;
  const dest = path.join(__dirname, "../public/brand/logo.svg");
  fs.writeFileSync(dest, file);
  console.log("wrote", dest, file.length, "bytes");
  // same path for inline use (stroke-draw animation needs the path in the DOM)
  const ts = `// Generated by scripts/vectorise-logo.mjs — do not edit by hand.\nexport const LOGO_VIEWBOX = "0 0 ${w} ${h}";\nexport const LOGO_PATH =\n  "${d}";\n`;
  const tsDest = path.join(__dirname, "../components/brand/logo-path.ts");
  fs.mkdirSync(path.dirname(tsDest), { recursive: true });
  fs.writeFileSync(tsDest, ts);
  console.log("wrote", tsDest);
});
